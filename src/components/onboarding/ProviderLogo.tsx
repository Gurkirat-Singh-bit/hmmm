export type ProviderLogoId = keyof typeof providerLogos | "custom";

/** Displays a provider mark from the app bundle without a remote image request. */
export function ProviderLogo({
  providerId,
  size = 17,
}: {
  providerId: ProviderLogoId;
  size?: number;
}) {
  if (providerId === "custom") {
    return (
      <Svg height={size} viewBox="0 0 24 24" width={size}>
        <Path
          d="m8 5-5 7 5 7m8-14 5 7-5 7m-2-16-4 18"
          fill="none"
          stroke="#1C1C1C"
          strokeLinecap="round"
          strokeLinejoin="round"
          strokeWidth={2.2}
        />
      </Svg>
    );
  }
  const logo = providerLogos[providerId];
  return (
    <Svg height={size} viewBox={logo.viewBox} width={size}>
      <Path d={logo.path} fill="#1C1C1C" />
    </Svg>
  );
}
